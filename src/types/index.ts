export type ChatRole = "user" | "assistant";

export interface ChatMessage {
  kind: "message";
  id: string;
  role: ChatRole;
  content: string;
  /** ISO 8601 string so it stays serializable when IndexedDB persistence lands. */
  createdAt: string;
}

/**
 * A system notice shown in the conversation (e.g. "AI integration is not
 * configured yet"). Kept separate from ChatMessage so real assistant replies
 * can never be confused for placeholders. Notices are session-only and are
 * never written to IndexedDB.
 */
export interface ChatNotice {
  kind: "notice";
  id: string;
  content: string;
  createdAt: string;
  /** "error" renders in red (e.g. save failures). Defaults to "info". */
  tone?: "info" | "error";
}

export type ChatItem = ChatMessage | ChatNotice;

export interface SuggestedPrompt {
  id: string;
  title: string;
  detail: string;
  prompt: string;
}

/** A locally persisted project. Stored in IndexedDB (schema: see AGENTS.md). */
export interface Project {
  id: string;
  name: string;
  /** ISO 8601 timestamps. */
  createdAt: string;
  updatedAt: string;
}

/**
 * A chat entry belonging to a project. Only role "user" is written by the
 * current implementation; "assistant" replies will be stored by the agent
 * integration task, never by placeholders or system notices.
 */
export interface ProjectMessage {
  id: string;
  projectId: string;
  role: ChatRole;
  content: string;
  createdAt: string;
}

/**
 * Reserved representation for files generated by the future build agent.
 * Deliberately not persisted yet: the agent task will bump the IndexedDB
 * schema version and add a "files" object store (see AGENTS.md).
 */
export interface ProjectFile {
  id: string;
  projectId: string;
  /** Relative path inside the generated project, e.g. "index.html". */
  path: string;
  /** Full text content of the file. */
  content: string;
  createdAt: string;
  updatedAt: string;
}
